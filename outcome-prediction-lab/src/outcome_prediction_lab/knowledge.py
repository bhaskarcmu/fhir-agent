def meps_categories(mapping: dict[str, list[str]]) -> dict[str, set[str]]:
    """Category -> the set of THREE-character codes that (approximately) indicate it."""
    return {cat: {c[:3] for c in codes} for cat, codes in mapping.items()}


def scores(icd3_codes: set[str]) -> dict[str, float]:
    """Knowledge-based features for one person's set of 3-character ICD-10 codes."""
    charlson = meps_categories(CHARLSON_ICD10_QUAN)
    elix = meps_categories(ELIXHAUSER_ICD10_QUAN)
    ch = {c for c, codes in charlson.items() if icd3_codes & codes}
    el = {c for c, codes in elix.items() if icd3_codes & codes}
    return {
        "hfrs": float(sum(HFRS_POINTS.get(c, 0.0) for c in icd3_codes)),
        "charlson_approx": float(sum(CHARLSON_WEIGHTS.get(c, 0) for c in ch)),
        "elixhauser_vw_approx": float(sum(ELIXHAUSER_WEIGHTS_VW.get(c, 0) for c in el)),
        "elixhauser_count_approx": float(len(el)),
    }
