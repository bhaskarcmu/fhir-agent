"""Interpretation for round 001 (concepts 3 and 5): which features matter globally, why ONE
patient's prediction is what it is, readable rules from a surrogate tree, and per-patient
missing-data action items.

Per-patient explanations use SHAP (TreeSHAP), which for a gradient-boosted model is exact in the
model's log-odds: the prediction = the average patient's log-odds + one contribution per feature.
A contribution of +0.7 log-odds multiplies the odds by e^0.7 ≈ 2.0 — so the narrative can say
"roughly doubled the odds" without approximating anything. Narratives are TEMPLATED from those
numbers, never generated by a language model (same rule as Phase 7 R20).
"""
from __future__ import annotations

import json
from pathlib import Path

import joblib
import numpy as np
import pandas as pd
from sklearn.metrics import r2_score, roc_auc_score
from sklearn.tree import DecisionTreeClassifier, DecisionTreeRegressor, export_text

from outcome_prediction_lab.data import build_lab_table
from outcome_prediction_lab.evaluate import TEST_PANELS, TRAIN_PANELS
from outcome_prediction_lab.features import DX_FLAGS, FEATURE_SETS, honest_frame

POVERTY = {1: "below the poverty line", 2: "near poor", 3: "low income", 4: "middle income", 5: "high income"}
DX_TEXT = {"hibpdx": "high blood pressure", "chddx": "coronary heart disease", "angidx": "angina",
           "midx": "a past heart attack", "ohrtdx": "other heart disease", "strkdx": "a past stroke",
           "emphdx": "emphysema", "diabdx": "diabetes", "arthdx": "arthritis", "asthdx": "asthma",
           "choldx": "high cholesterol"}


def describe(feature: str, value) -> str:
    """Plain-language text for one feature value. Missing values say so."""
    if feature.startswith("codes_"):   # codes_all: the summed learned code pattern
        return "their overall pattern of diagnosis and drug codes"
    if value is None or (isinstance(value, float) and np.isnan(value)):
        return f"{feature} not recorded"
    v = float(value)
    text = {
        "agey1x": f"age {v:.0f}",
        "sex": "male" if v == 1 else "female",
        "ipdisy1": f"{v:.0f} hospital stay{'s' if v != 1 else ''} last year",
        "ipngtdy1": f"{v:.0f} night{'s' if v != 1 else ''} in hospital last year",
        "ertoty1": f"{v:.0f} ER visit{'s' if v != 1 else ''} last year",
        "obtotvy1": f"{v:.0f} office visit{'s' if v != 1 else ''} last year",
        "optotvy1": f"{v:.0f} hospital outpatient visit{'s' if v != 1 else ''}",
        "hhtotdy1": f"{v:.0f} home-health day{'s' if v != 1 else ''}",
        "rxtoty1": f"{v:.0f} prescription fill{'s' if v != 1 else ''} last year",
        "totexpy1": f"${v:,.0f} of health spending last year",
        "povcaty1": f"household income {POVERTY.get(int(v), 'unknown')}",
        "inscovy1": {1: "private insurance", 2: "public insurance only", 3: "uninsured"}.get(int(v), "insurance unknown"),
        "mcrevy1": "on Medicare" if v == 1 else "not on Medicare",
        "mcdevy1": "on Medicaid" if v == 1 else "not on Medicaid",
        "hfrs": f"hospital frailty score {v:.1f}",
        "charlson_approx": f"Charlson comorbidity score {v:.0f}",
        "elixhauser_vw_approx": f"Elixhauser comorbidity score {v:.0f}",
        "elixhauser_count_approx": f"{v:.0f} Elixhauser comorbidit{'ies' if v != 1 else 'y'}",
        "n_icd": f"{v:.0f} distinct diagnosis code{'s' if v != 1 else ''}",
        "n_ccsr_systems": f"conditions in {v:.0f} body system{'s' if v != 1 else ''}",
        "n_rx_classes": f"{v:.0f} distinct drug class{'es' if v != 1 else ''}",
        "n_suppressed_codes": f"{v:.0f} suppressed diagnosis code{'s' if v != 1 else ''}",
        "regiony1": {1: "Northeast", 2: "Midwest", 3: "South", 4: "West"}.get(int(v), "region unknown"),
        "racethx": "race/ethnicity group " + str(int(v)),
    }.get(feature)
    if text is None and feature in DX_FLAGS:
        text = ("has " if v == 1 else "no ") + DX_TEXT[feature]
    return text or f"{feature} = {v:g}"


def _odds_phrase(phi: float) -> str:
    mult = float(np.exp(phi))
    return f"odds ×{mult:.2f}" if mult >= 1 else f"odds ×{mult:.2f}"


def code_drivers(pipe, row: pd.DataFrame, code_phi: np.ndarray, k: int = 3) -> list[str]:
    """Which of THIS patient's own codes drive the learned code pattern. An LSA dimension is a
    weighted sum of the patient's TF-IDF code weights, so each dimension's contribution is split
    across the codes in proportion to their share of that sum — an approximation (linear
    attribution through the SVD), labelled as such in the narrative."""
    codes = pipe.named_steps["cols"].named_transformers_["codes"]
    tfidf, svd = codes.named_steps["tfidf"], codes.named_steps["svd"]
    x = tfidf.transform(row["tokens"]).toarray()[0]
    present = np.nonzero(x)[0]
    if len(present) == 0:
        return []
    parts = x[present][:, None] * svd.components_[:, present].T          # (codes, dims)
    z = parts.sum(axis=0)
    share = np.divide(parts, z, out=np.zeros_like(parts), where=np.abs(z) > 1e-12)
    per_code = (share * code_phi[None, :]).sum(axis=1)
    vocab = tfidf.get_feature_names_out()[present]
    top = np.argsort(-np.abs(per_code))[:k]
    return [f"{vocab[i].removeprefix('icd')} ({_odds_phrase(per_code[i])})" for i in top if abs(per_code[i]) > 0.01]


def narrative(prob: float, base: float, row: pd.Series, contribs: dict[str, float], k: int = 3,
              code_detail: list[str] | None = None) -> str:
    contribs = dict(contribs)
    code_keys = [f for f in contribs if f.startswith("codes_")]
    if code_keys:                                    # one entry for the whole learned code pattern
        contribs["codes_all"] = sum(contribs.pop(f) for f in code_keys)
    up = sorted(((f, c) for f, c in contribs.items() if c > 0), key=lambda x: -x[1])[:k]
    down = sorted(((f, c) for f, c in contribs.items() if c < 0), key=lambda x: x[1])[:k]
    fmt = lambda items: "; ".join(f"{describe(f, row.get(f))} ({_odds_phrase(c)})" for f, c in items)  # noqa: E731
    lines = [f"Estimated 12-month hospitalization risk {prob:.0%} (model baseline {base:.0%})."]
    if up:
        lines.append(f"Raised most by: {fmt(up)}.")
    if down:
        lines.append(f"Lowered most by: {fmt(down)}.")
    if code_detail:
        lines.append(f"Codes driving the code pattern (approximate): {', '.join(code_detail)}.")
    lines.append("These describe what the model weighed, not causes; a planning aid, not a diagnosis.")
    return " ".join(lines)


def action_items(model, row: pd.DataFrame, threshold_points: float = 2.0) -> list[str]:
    """Value of information: for a field the patient record lacks, how far could the estimate
    move across that field's plausible values? Large swings become data-completeness prompts —
    never clinical recommendations."""
    items = []
    probe = {"povcaty1": ("household income (for the poverty category)", [1, 2, 3, 4, 5])}
    for col, (label, values) in probe.items():
        if not pd.isna(row[col].iloc[0]):
            continue
        preds = []
        for v in values:
            r = row.copy(); r[col] = v
            preds.append(float(model.predict_proba(r)[:, 1][0]))
        lo, hi = min(preds), max(preds)
        if (hi - lo) * 100 >= threshold_points:
            items.append(f"Record {label}: depending on it, this estimate ranges from {lo:.0%} to {hi:.0%}.")
    return items


def run(round_dir: Path, res: dict) -> dict:
    import shap

    t = build_lab_table()
    h = honest_frame(t)
    train = h.panel.isin(TRAIN_PANELS).to_numpy()
    test = h.panel.isin(TEST_PANELS).to_numpy()
    from outcome_prediction_lab.round_001 import fitted_model_path
    pipe = joblib.load(fitted_model_path())
    cats, nums = FEATURE_SETS["portable+knowledge"]
    text = res.get("any_stay_text_choice")
    n_codes = {None: 0, "lsa": 32, "ae": 16, "dae": 16}[text]
    names = cats + nums + [f"codes_{i}" for i in range(n_codes)]
    gbm = pipe.named_steps["clf"]

    Xte = h[test].reset_index(drop=True)
    yte = Xte.label_hosp_12m.to_numpy()
    sample = Xte.sample(n=min(3000, len(Xte)), random_state=0)
    Z = pipe.named_steps["cols"].transform(sample)
    explainer = shap.TreeExplainer(gbm)
    phi = explainer.shap_values(Z)
    base_logodds = float(np.ravel(explainer.expected_value)[0])

    # Global importance: mean |contribution|; learned code dimensions grouped as one "feature".
    imp = pd.Series(np.abs(phi).mean(axis=0), index=names)
    grouped = imp[[n for n in names if not n.startswith("codes_")]].to_dict()
    if n_codes:
        grouped["(learned code pattern, all dims)"] = float(imp[[n for n in names if n.startswith("codes_")]].sum())
    global_importance = dict(sorted(grouped.items(), key=lambda kv: -kv[1]))
    # Direction: correlation of each feature's value with its contribution (+ = higher raises risk).
    direction = {}
    for i, n in enumerate(names[: len(cats) + len(nums)]):
        v = pd.to_numeric(pd.Series(Z[:, i]), errors="coerce")
        ok = v.notna().to_numpy() & (v.nunique() > 1)
        direction[n] = float(np.corrcoef(v[ok], phi[ok, i])[0, 1]) if ok.sum() > 10 else None

    # Three example patients: low, high, very high predicted risk.
    p_all = pipe.predict_proba(Xte)[:, 1]
    order = np.argsort(p_all)
    examples = {}
    for label, q in (("low risk", 0.20), ("high risk", 0.92), ("very high risk", 0.995)):
        i = int(order[int(q * (len(order) - 1))])
        row = Xte.iloc[[i]]
        z = pipe.named_steps["cols"].transform(row)
        sv = explainer.shap_values(z)[0]
        contrib = dict(zip(names, sv))
        detail = code_drivers(pipe, row, sv[len(cats) + len(nums):]) if n_codes else None
        examples[label] = {"predicted": float(p_all[i]), "hospitalized_in_year_2": int(yte[i]),
                           "codes": row.tokens.iloc[0],
                           "narrative": narrative(float(p_all[i]), float(1 / (1 + np.exp(-base_logodds))),
                                                  row.iloc[0], contrib, code_detail=detail)}
    # A patient whose income is unknown in production: value-of-information action item.
    voi_row = Xte.iloc[[int(order[int(0.92 * (len(order) - 1))])]].copy()
    voi_row["povcaty1"] = np.nan
    voi = {"predicted_with_income_unknown": float(pipe.predict_proba(voi_row)[:, 1][0]),
           "action_items": action_items(pipe, voi_row)}

    # Surrogate: one shallow tree imitating the model (readable rules + fidelity).
    Xtr = h[train].reset_index(drop=True)
    dense = cats + nums
    target = pipe.predict_proba(Xtr)[:, 1]
    surrogate = DecisionTreeRegressor(max_depth=3, min_samples_leaf=300, random_state=0).fit(Xtr[dense], target)
    fidelity = float(r2_score(pipe.predict_proba(Xte)[:, 1], surrogate.predict(Xte[dense])))
    rules = export_text(surrogate, feature_names=dense, decimals=1)
    # An interpretable model in its own right: one depth-4 tree trained on the label.
    tree = DecisionTreeClassifier(max_depth=4, min_samples_leaf=200, random_state=0).fit(Xtr[dense], Xtr.label_hosp_12m)
    tree_auroc = float(roc_auc_score(yte, tree.predict_proba(Xte[dense])[:, 1]))

    out = {"model": "any_stay/new-portable", "global_importance_mean_abs_logodds": global_importance,
           "direction_corr_value_vs_contribution": direction, "examples": examples, "value_of_information": voi,
           "surrogate_tree": {"depth": 3, "fidelity_r2_on_test": fidelity, "rules": rules},
           "single_tree_model": {"depth": 4, "test_auroc": tree_auroc,
                                 "rules": export_text(tree, feature_names=dense, decimals=1)}}
    (round_dir / "explanations.json").write_text(json.dumps(out, indent=2) + "\n")
    print("top features:", list(global_importance)[:8])
    print("surrogate fidelity R2:", round(fidelity, 3), "| single tree AUROC:", round(tree_auroc, 3))
    for k, v in examples.items():
        print(f"[{k}] {v['narrative']}")
    print("action items:", voi["action_items"])
    return {k: v for k, v in out.items() if k != "examples"} | {"examples": examples}
