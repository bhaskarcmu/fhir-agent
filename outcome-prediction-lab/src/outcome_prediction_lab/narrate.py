"""Self-explanatory per-patient narratives (round 002).

For one patient: the estimate in plain words, compared with meaningful groups of real adults; the
main reasons it is high or low — each with the observed rate for comparable adults — with every
code replaced by its full name; data gaps and how much they matter; and what the estimate is not.

How the reasons are found: SHAP (TreeSHAP) splits the gradient-boosted model's prediction exactly
into one contribution per input (in log-odds). The learned code pattern (LSA dimensions) is traced
back to the patient's own codes — an approximation, linear through the SVD. Contributions decide
WHICH reasons are named and in what order; the sentences themselves quote observed group rates,
not log-odds, so a reader never needs a statistics glossary.

Comparison groups are OBSERVED year-2 rates among adults in the training panels (21–25).
Narratives are TEMPLATED from those numbers, never generated by a language model (Phase 7 R20).
Two deliberate omissions: race/ethnicity is never narrated per patient (its influence belongs in
aggregate fairness reporting), and a patient's actual outcome is never shown — an explanation is
not a performance look at the test panels.
"""
from __future__ import annotations

from dataclasses import dataclass, field

import numpy as np
import pandas as pd

from outcome_prediction_lab.evaluate import TRAIN_PANELS
from outcome_prediction_lab.features import DX_FLAGS
from outcome_prediction_lab.vocabulary import name_token

OUTCOMES = {
    "label_hosp_12m": "at least one overnight hospital stay",
    "admit_y2": "an overnight hospital admission",
    "admit_nonobstetric_y2": "an overnight hospital stay that isn't related to pregnancy or childbirth",
    "admit_via_er_y2": "a hospital admission through the emergency room",
    "any_ed_y2": "at least one emergency-room visit",
    "high_cost_y2": "health care costs among the highest 10% of adults",
    "died_y2": "death",
    "lost_insurance_y2": "losing their health insurance",
}
# Short form for the comparison groups, after the outcome has been named in full once.
OUTCOMES_SHORT = {
    "label_hosp_12m": "were hospitalised", "admit_y2": "were hospitalised",
    "admit_nonobstetric_y2": "were hospitalised for reasons other than childbirth",
    "admit_via_er_y2": "were admitted through the ER", "any_ed_y2": "visited the ER",
    "high_cost_y2": "became high-cost", "died_y2": "died", "lost_insurance_y2": "lost their insurance",
}
CONDITION = {"hibpdx": "high blood pressure", "chddx": "coronary heart disease", "angidx": "angina",
             "midx": "a heart attack", "ohrtdx": "another heart condition", "strkdx": "a stroke",
             "emphdx": "emphysema", "diabdx": "diabetes", "arthdx": "arthritis", "asthdx": "asthma",
             "choldx": "high cholesterol"}
INCOME = {1: "household income below the federal poverty line", 2: "household income just above the poverty line",
          3: "low household income", 4: "middle household income", 5: "high household income"}
REGION = {1: "the Northeast", 2: "the Midwest", 3: "the South", 4: "the West"}
NOT_NARRATED = {"racethx", "n_suppressed_codes"}
AGE_BANDS = [(18, 44, "18–44"), (45, 64, "45–64"), (65, 74, "65–74"), (75, 200, "75 and over")]
ELIX_BUCKETS = [(0, 0, "none"), (1, 2, "1–2"), (3, 4, "3–4"), (5, 999, "5 or more")]
DX_BUCKETS = [(0, 0, "no recorded diagnoses"), (1, 2, "1–2 diagnoses"), (3, 5, "3–5 diagnoses"),
              (6, 9, "6–9 diagnoses"), (10, 999, "10 or more diagnoses")]


def pct(p: float) -> str:
    if p < 0.01:
        return "under 1%"
    return f"{p * 100:.1f}%" if p < 0.10 else f"{p * 100:.0f}%"


def relative(p: float, ref: float) -> str:
    r = p / ref
    if 0.85 <= r <= 1.15:
        return "about the same as"
    if r > 1:
        return f"about {r:.1f} times" if r < 10 else f"more than {int(r)} times"
    return f"about {round(r * 100)}% of"


def band(age: float) -> str:
    return next(lab for lo, hi, lab in AGE_BANDS if lo <= age <= hi)


def elix_bucket(n: float) -> str:
    return next(lab for lo, hi, lab in ELIX_BUCKETS if lo <= n <= hi)


def dx_bucket(n: float) -> str:
    return next(lab for lo, hi, lab in DX_BUCKETS if lo <= n <= hi)


@dataclass
class Aggregates:
    """Observed year-2 rates in the training panels — the 'meaningful aggregates' quoted."""
    label: str
    overall: float
    by_band_sex: dict = field(default_factory=dict)
    by_band: dict = field(default_factory=dict)
    prior_stay: dict = field(default_factory=dict)
    prior_er: dict = field(default_factory=dict)
    by_dx_bucket: dict = field(default_factory=dict)
    by_token: dict = field(default_factory=dict)
    by_condition: dict = field(default_factory=dict)
    by_elix: dict = field(default_factory=dict)
    medians: dict = field(default_factory=dict)
    hfrs_sorted: np.ndarray = None
    risk_sorted: np.ndarray = None

    @classmethod
    def from_training(cls, frame: pd.DataFrame, label: str, risk: np.ndarray | None = None, min_n: int = 100):
        t = frame[frame.panel.isin(TRAIN_PANELS) & frame[label].notna()]
        y = t[label]
        agg = cls(label=label, overall=float(y.mean()))
        bands = t.agey1x.map(band)
        agg.by_band = y.groupby(bands).mean().to_dict()
        agg.by_band_sex = y.groupby([bands, t.sex]).mean().to_dict()
        agg.prior_stay = y.groupby(t.ipdisy1 > 0).mean().to_dict()
        agg.prior_er = y.groupby(t.ertoty1 > 0).mean().to_dict()
        agg.by_dx_bucket = y.groupby(t.n_icd.map(dx_bucket)).mean().to_dict()
        for col in DX_FLAGS:
            agg.by_condition[col] = float(y[t[col] == 1].mean())
        exploded = t[["tokens"]].assign(y=y).assign(tok=t.tokens.str.split()).explode("tok").dropna(subset=["tok"])
        stats = exploded.groupby("tok").y.agg(["mean", "size"])
        agg.by_token = stats[stats["size"] >= min_n]["mean"].to_dict()
        agg.by_elix = y.groupby(t.elixhauser_count_approx.map(elix_bucket)).mean().to_dict()
        agg.medians = {c: float(t[c].median()) for c in ("totexpy1", "rxtoty1", "obtotvy1", "n_rx_classes")}
        agg.hfrs_sorted = np.sort(t.hfrs.to_numpy())
        agg.risk_sorted = None if risk is None else np.sort(risk)
        return agg

    def percentile_of(self, sorted_values: np.ndarray, v: float) -> int:
        return int(round(100 * np.searchsorted(sorted_values, v, side="right") / len(sorted_values)))


def _plural(n: float, word: str, plural: str | None = None) -> str:
    n = int(round(n))
    return f"{n} {word if n == 1 else (plural or word + 's')}"


def reason(feature: str, row: pd.Series, up: bool, agg: Aggregates, outcome: str, vocab: dict) -> str | None:
    """One plain-language reason, with a comparison group where one exists."""
    v = row.get(feature)
    if feature in NOT_NARRATED or v is None or pd.isna(v):
        return None          # missing income is covered by its own data-gap sentence
    had = outcome            # the short form, e.g. "were hospitalised"
    he, has = ("he", "has") if row.get("sex") == 1 else ("she", "has")
    if feature == "agey1x":
        b = band(v)
        return f"being {int(v)} years old ({pct(agg.by_band[b])} of adults aged {b} {had} the following year)"
    if feature == "sex":
        return "being a man" if v == 1 else "being a woman"
    if feature == "ipdisy1":
        if v > 0:
            return (f"{_plural(v, 'overnight hospital stay')} in the past year ({pct(agg.prior_stay[True])} of adults "
                    f"with a hospital stay in the past year {had} the following year)")
        return f"no hospital stays in the past year (only {pct(agg.prior_stay[False])} of adults without one {had})"
    if feature == "ipngtdy1":
        return f"{_plural(v, 'night')} spent in hospital in the past year" if v > 0 else "no nights in hospital in the past year"
    if feature == "ertoty1":
        if v > 0:
            return (f"{_plural(v, 'emergency-room visit')} in the past year ({pct(agg.prior_er[True])} of adults "
                    f"with an ER visit {had} the following year)")
        return f"no emergency-room visits in the past year ({pct(agg.prior_er[False])} of adults without one {had})"
    if feature == "obtotvy1":
        return f"{_plural(v, 'doctor’s-office visit')} in the past year (the typical adult had {int(agg.medians['obtotvy1'])})"
    if feature == "optotvy1":
        return f"{_plural(v, 'hospital outpatient visit')} in the past year" if v > 0 else "no hospital outpatient visits"
    if feature == "hhtotdy1":
        return f"{_plural(v, 'day')} of home health care in the past year" if v > 0 else None
    if feature == "rxtoty1":
        return f"{_plural(v, 'prescription fill')} in the past year (the typical adult had {int(agg.medians['rxtoty1'])})"
    if feature == "totexpy1":
        return f"${v:,.0f} of health care spending in the past year (the typical adult’s was ${agg.medians['totexpy1']:,.0f})"
    if feature == "povcaty1":
        return INCOME.get(int(v))
    if feature == "inscovy1":
        return {1: "having private health insurance", 2: "having only public health insurance",
                3: "having no health insurance"}.get(int(v))
    if feature == "mcrevy1":
        return "being enrolled in Medicare" if v == 1 else "not being enrolled in Medicare"
    if feature == "mcdevy1":
        return "being enrolled in Medicaid" if v == 1 else "not being enrolled in Medicaid"
    if feature == "regiony1":
        return f"living in {REGION.get(int(v), 'an unknown region')}"
    if feature in DX_FLAGS:
        cond = CONDITION[feature]
        if v == 1:
            return f"having been told {he} {has} {cond} ({pct(agg.by_condition[feature])} of adults with {cond} {had})"
        return f"no history of {cond}"
    if feature == "hfrs":
        if v <= 0:
            return "no frailty-related diagnoses"
        return (f"diagnoses associated with frailty (a hospital frailty score of {v:.1f}, higher than "
                f"{agg.percentile_of(agg.hfrs_sorted, v)}% of adults)")
    if feature == "charlson_approx":
        return f"a Charlson comorbidity score of {v:.0f} (a standard summary of serious long-term illnesses)" if v > 0 else "no serious long-term illnesses on the Charlson list"
    if feature in ("elixhauser_vw_approx", "elixhauser_count_approx"):
        n = row.get("elixhauser_count_approx", 0)
        if n <= 0:
            return "no conditions on the Elixhauser comorbidity list (a standard list of serious long-term illnesses)"
        b = elix_bucket(n)
        return (f"{_plural(n, 'serious long-term condition')} on the Elixhauser comorbidity list "
                f"({pct(agg.by_elix[b])} of adults with {b} such conditions {had})")
    if feature == "n_icd":
        bucket = dx_bucket(v)
        return f"{_plural(v, 'different diagnosis', 'different diagnoses')} recorded in the past year ({pct(agg.by_dx_bucket[bucket])} of adults with {bucket} {had})"
    if feature == "n_ccsr_systems":
        systems = sorted({vocab['body_system'].get(t[:3]) for t in row.get('tokens', '').split()
                          if not t.startswith(('icd', 'rx')) and t[:3] in vocab['body_system']} - {None})
        listed = f": {', '.join(systems[:4])}" + (" and others" if len(systems) > 4 else "") if systems else ""
        return f"health problems in {_plural(v, 'body system')}{listed}" if v > 0 else "no recorded health problems"
    if feature == "n_rx_classes":
        if v <= 0:
            return "no prescription medicines"
        return (f"medicines from {_plural(v, 'different drug class', 'different drug classes')} "
                f"(the typical adult takes medicines from {int(agg.medians['n_rx_classes'])})")
    return None


def _code_phrase(token: str, agg: Aggregates, outcome: str, vocab: dict, up: bool = True) -> str:
    kind, name = name_token(token, vocab)
    name = name[:1].lower() + name[1:] if kind != "medicine class" else name
    rate = agg.by_token.get(token)
    tail = ""
    if rate is not None:
        tail = f" ({pct(rate)} of adults with this {outcome}"
        # Marginal vs conditional: a group can be above average on its own yet, given the rest of
        # this patient's record, point to LOWER risk (or vice versa). Say so instead of leaving a puzzle.
        if not up and rate > agg.overall:
            tail += (" — above the average on its own, but for someone with the rest of this patient’s "
                     "record it points to lower risk")
        elif up and rate < agg.overall:
            tail += " — below average on its own, but in combination with the rest of this record it points to higher risk"
        tail += ")"
    if kind == "medicine class":
        return f"taking a medicine of the class “{name}”{tail}"
    if kind == "diagnosis":
        return f"a diagnosis of {name}{tail}"
    return f"health problems in the group “{name}”{tail}"


def _join(items: list[str]) -> str:
    items = [i for i in items if i]
    if len(items) <= 1:
        return "".join(items)
    return "; ".join(items[:-1]) + "; and " + items[-1]


def narrative(row: pd.DataFrame, p: float, contribs: dict[str, float], code_contribs: dict[str, float],
              agg: Aggregates, vocab: dict, outcome: str, income_range: tuple[float, float] | None = None,
              k: int = 3, short: str | None = None) -> str:
    short = short or OUTCOMES_SHORT.get(agg.label, f"had {outcome}")
    r = row.iloc[0]
    age, sex = r.agey1x, r.sex
    who = f"{int(age)}-year-old {'man' if sex == 1 else 'woman'}"
    he = "he" if sex == 1 else "she"
    b = band(age)
    grp = agg.by_band_sex.get((b, sex), agg.by_band[b])
    s1 = (f"This {who} has an estimated {pct(p)} chance of {outcome} in the next 12 months — "
          f"{relative(p, agg.overall)} the average adult ({pct(agg.overall)}), and "
          f"{relative(p, grp)} {'men' if sex == 1 else 'women'} aged {b} ({pct(grp)}).")
    if agg.risk_sorted is not None:
        rank = min(agg.percentile_of(agg.risk_sorted, p), 99)
        s1 += f" That puts {'him' if sex == 1 else 'her'} above {rank}% of adults." if rank >= 1 else \
              f" That puts {'him' if sex == 1 else 'her'} among the lowest-risk 1% of adults."
    _ = he

    # Candidate reasons: ordinary features, plus each of the patient's own codes separately.
    items = [(f, c, False) for f, c in contribs.items() if not f.startswith(("codes_", "text_"))]
    items += [(tok, c, True) for tok, c in code_contribs.items()]
    def render(f, is_code, up):
        return _code_phrase(f, agg, short, vocab, up) if is_code else reason(f, r, up, agg, short, vocab)
    def unique(phrases):                      # two features can share one phrase (Elixhauser score/count)
        return [x for x in dict.fromkeys(phrases) if x]
    ups = unique(render(f, ic, True) for f, c, ic in sorted(items, key=lambda x: -x[1]) if c > 0.02)[:k]
    downs = unique(render(f, ic, False) for f, c, ic in sorted(items, key=lambda x: x[1]) if c < -0.02)[:k - 1]

    parts = [s1]
    if ups:
        parts.append(f"The estimate is pushed up mainly by {_join(ups)}.")
    if downs:
        parts.append(f"It is held down by {_join(downs)}.")
    if income_range and income_range[1] - income_range[0] >= 0.02:
        parts.append(f"Household income isn't recorded; depending on it, the estimate would be between "
                     f"{pct(income_range[0])} and {pct(income_range[1])} — worth recording.")
    parts.append("This is a planning estimate from patterns in national survey data: it shows what the "
                 "model weighed, not what causes illness, and it is not a diagnosis.")
    return " ".join(parts)


class Narrator:
    """Explains patients for one fitted pipeline (gradient boosting, optional code-token LSA)."""

    def __init__(self, pipe, cfg: dict, frame: pd.DataFrame, vocab: dict):
        import shap
        from outcome_prediction_lab.features import FEATURE_SETS, TEXT_BLOCKS, _kinds
        self.pipe, self.cfg, self.vocab = pipe, cfg, vocab
        cats, nums = FEATURE_SETS[cfg["features"]]
        self.dense = cats + nums
        names = list(self.dense)
        for kind in _kinds(cfg.get("text")):
            prefix = "codes_" if kind in ("lsa", "ae", "dae") else f"text_{kind}_"
            names += [f"{prefix}{i}" for i in range(TEXT_BLOCKS[kind][2])]
        self.names = names
        self.explainer = shap.TreeExplainer(pipe.named_steps["clf"])
        self.outcome = cfg.get("outcome_phrase") or OUTCOMES.get(cfg["label"], cfg["label"])
        train = frame[frame.panel.isin(TRAIN_PANELS) & frame[cfg["label"]].notna()]
        risk = pipe.predict_proba(train)[:, 1]
        self.agg = Aggregates.from_training(frame, cfg["label"], risk)

    def _code_contribs(self, row: pd.DataFrame, phi_codes: np.ndarray) -> dict[str, float]:
        if "codes" not in self.pipe.named_steps["cols"].named_transformers_ or not len(phi_codes):
            return {}
        codes = self.pipe.named_steps["cols"].named_transformers_["codes"]
        tfidf, svd = codes.named_steps["tfidf"], codes.named_steps["svd"]
        x = tfidf.transform(row["tokens"]).toarray()[0]
        present = np.nonzero(x)[0]
        if not len(present):
            return {}
        parts = x[present][:, None] * svd.components_[:, present].T
        z = parts.sum(axis=0)
        share = np.divide(parts, z, out=np.zeros_like(parts), where=np.abs(z) > 1e-12)
        per = (share * phi_codes[None, :]).sum(axis=1)
        vocab = tfidf.get_feature_names_out()[present]
        return dict(zip(vocab, per))

    def explain(self, row: pd.DataFrame) -> dict:
        z = self.pipe.named_steps["cols"].transform(row)
        phi = self.explainer.shap_values(z)[0]
        contribs = dict(zip(self.names, phi))
        code_idx = [i for i, n in enumerate(self.names) if n.startswith("codes_")]
        code_contribs = self._code_contribs(row, phi[code_idx]) if code_idx else {}
        p = float(self.pipe.predict_proba(row)[:, 1][0])
        income = None
        if pd.isna(row.povcaty1.iloc[0]):
            preds = []
            for v in (1, 2, 3, 4, 5):
                r = row.copy(); r["povcaty1"] = v
                preds.append(float(self.pipe.predict_proba(r)[:, 1][0]))
            income = (min(preds), max(preds))
        return {"predicted": p, "narrative": narrative(row, p, contribs, code_contribs, self.agg, self.vocab,
                                                       self.outcome, income,
                                                       short=OUTCOMES_SHORT.get(self.cfg["label"]))}
